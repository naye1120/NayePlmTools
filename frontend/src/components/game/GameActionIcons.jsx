/* [CN-FORK] v0.5.2.112 游戏磁贴上四颗操作按钮的专用图标
 *
 * 为什么不用 lucide 现成的 Download / Camera / Pencil / Tag：
 *   那四颗是**占位**（v0.5.2.99 上线时功能没接后端，按钮 aria-disabled）。现在四个动作都
 *   落地了，语义也变了，继续沿用会把用户带偏：
 *     · Download  → 存档管理：不是「下载」，是「存档」（上传+下载+自动同步都在里面）
 *     · Camera    → 多媒体管理：截图**和视频**，相机不表达视频
 *     · Pencil    → 名称修改：除了改名还要**换磁贴背景**，光一支笔不够
 *     · Tag       → 待定：标签语义已经被「来源/格式徽标」占了，再挂一个 Tag 会撞
 *
 * 画法约定（与 lucide 完全一致，所以四颗新图标和站内其余图标能并排而不打架）：
 *   · viewBox 0 0 24 24；fill="none" + stroke="currentColor"
 *   · 线宽 1.8（lucide 默认 2，但磁贴上按钮只有 16px，1.8 在小尺寸下更不容易糊成一团）
 *   · round 端点 + round 拐角
 *   · 尺寸交给 className（默认 w-4 h-4），颜色一律 currentColor —— 这样悬停变白、
 *     .is-focus 描边、浅色主题豁免这三条既有机制**一行都不用改**就自动生效。
 *
 * 四颗图标的辨识点（16px 下必须一眼分得开，所以刻意选了四种不同的「外轮廓」）：
 *   存档   = 记忆卡（圆角矩形 + 卡口）+ 向下箭头   → 横向矩形轮廓
 *   多媒体 = 叠两张卡 + 播放三角                    → 错位的双矩形轮廓
 *   改名   = 磁贴（方）+ 压角的铅笔                 → 正方形轮廓 + 一根斜线
 *   待定   = 圆角方框 + 三点                        → 正方形轮廓 + 三个点
 * 后两颗都是方框，但一个被斜线破开、一个里面是点阵，远看不会混。
 */

const base = {
  viewBox: '0 0 24 24',
  fill: 'none',
  stroke: 'currentColor',
  strokeWidth: 1.8,
  strokeLinecap: 'round',
  strokeLinejoin: 'round',
  xmlns: 'http://www.w3.org/2000/svg',
}

/* 存档管理：PS 玩家对「存档」的第一联想是记忆卡 —— 一个带插入卡口的圆角矩形，
 * 中间压一个向下的箭头（写入存档的方向；上传/下载两个方向都由这一个图形统辖，
 * 不画双向箭头是因为 16px 下双箭头会退化成一根竖线）。 */
export function SaveManagerIcon({ className = 'w-4 h-4' }) {
  return (
    <svg {...base} className={className} aria-hidden="true">
      {/* 记忆卡本体 */}
      <rect x="3" y="4" width="18" height="16" rx="3" />
      {/* 顶部插入卡口（两侧竖线 + 一条横线，做出「这是一张卡不是一封信」的厚度感） */}
      <path d="M7.5 4v4.5h9V4" />
      {/* 向下的写入箭头 */}
      <path d="M12 11.5v6" />
      <path d="M9.5 15 12 17.5 14.5 15" />
    </svg>
  )
}

/* 多媒体管理：**叠两张卡**表示「这是一个媒体库（很多张）」，前面那张里面放播放三角
 * 表示「里面有视频」。单画一个相框（lucide Image）不表达视频；单画播放键又不表达截图。
 * 后面那张只画左上到右下的两条边（开口路径），是 lucide Copy 系列的成熟做法 ——
 * 既读得出「后面还有一张」，又不跟前面那张的边框糊在一起。 */
export function MediaManagerIcon({ className = 'w-4 h-4' }) {
  return (
    <svg {...base} className={className} aria-hidden="true">
      {/* 后面那张：只留左上角两条边 */}
      <path d="M8.5 3.5h9A2.5 2.5 0 0 1 20 6v9" />
      {/* 前面那张 */}
      <rect x="4" y="7.5" width="12.5" height="12.5" rx="2.5" />
      {/* 播放三角（闭合路径，走描边） */}
      <path d="M8.6 11.6 13.4 13.75 8.6 15.9Z" />
    </svg>
  )
}

/* 名称修改：一支斜放的**笔** + 它正要写的那条**名字基线**。
 *
 * [CN-FORK] 这颗图标画废了两版，记下来免得以后再走回头路：
 *   第一版「磁贴 + 短铅笔」：笔身 3.4、笔尖 3.1，几乎等长 → 48px 下读成「对话气泡的尾巴」。
 *   第二版「磁贴 + 加长铅笔斜穿右下角」：把笔身拉到 6.5、笔尖 2.6，坐标按半宽 0.85 手推 ——
 *   还是不行。根因不是比例，是**画了两个图形**：16px 时磁贴吃掉 13×13，剩下的空间里那支笔
 *   只有 ~3px 宽，必然和磁贴的圆角糊在一起，怎么调都是「一个方框带个尾巴」。
 *   第三版（本图）**去掉磁贴**：只留笔和它写的那条线。轮廓变成「一根斜线 + 一根横线」，
 *   和另外三颗（横向矩形 / 错位双矩形 / 方框加点）在剪影上完全不撞，缩到 16px 也清楚。
 *
 * 为什么磁贴背景这一半没有体现在图标里：这颗按钮做两件事（改名 + 换背景），但两者都是
 * 「改这张卡片本身」，而**卡片就在图标外面**——用户看的是磁贴上的按钮，不需要图标再画一遍磁贴。
 * 语义分工交给弹窗标题，图标只负责「这里能改东西」。
 *
 * 坐标同样是手推的（笔身半宽 1.15，笔尖 2.6、笔身 12.4）：
 *   笔尖 T(5.5,18.5) → 基座 (6.53,15.85)/(8.15,17.47) → 笔尾圆角 (15.29,7.09)/(16.91,8.71) */
export function RenameTileIcon({ className = 'w-4 h-4' }) {
  return (
    <svg {...base} className={className} aria-hidden="true">
      {/* 笔：笔尖在左下，笔尾在右上 */}
      <path d="M5.5 18.5 8.15 17.47 16.91 8.71a1.15 1.15 0 0 1-1.62-1.62l-8.76 8.76z" />
      {/* 名字基线（笔正要落笔的那一行） */}
      <path d="M4 20.5h16" />
    </svg>
  )
}

/* 第四个功能位（待定）：圆角方框 + 三个点。
 * 用户还没定这个位置做什么，所以图标必须是**中性的「这里还有一格」**，不能暗示任何具体功能
 * （曾经想用灯泡/扳手/星星，都会让用户以为这就是最终语义）。三点是「更多」的通用写法，
 * 且与上面三颗的实心图形在轮廓上不冲突。 */
export function PendingSlotIcon({ className = 'w-4 h-4' }) {
  return (
    <svg {...base} className={className} aria-hidden="true">
      <rect x="3" y="3" width="18" height="18" rx="4.5" />
      {/* 三个点必须实心，且要显式 stroke="none" —— 否则会继承父级的描边，变成三个小圆圈 */}
      <circle cx="8.4" cy="12" r="1.05" fill="currentColor" stroke="none" />
      <circle cx="12" cy="12" r="1.05" fill="currentColor" stroke="none" />
      <circle cx="15.6" cy="12" r="1.05" fill="currentColor" stroke="none" />
    </svg>
  )
}

