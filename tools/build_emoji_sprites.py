#!/usr/bin/env python3
"""Generate bundled Twemoji sprites from the pinned upstream archive (Pillow required).

Normal app builds use the checked-in outputs and require no download or Pillow.
Usage: python3 tools/build_emoji_sprites.py scratch/twemoji-v15.1.0.tar.gz
"""
import hashlib
import io
import json
import math
from pathlib import Path
import sys
import tarfile
from PIL import Image

ARCHIVE_SHA256 = 'ffa39215bb14fbedf29743c5e7b897c0a2f06070f27009c6ec716ff080032d19'
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'frontend/src/assets/emoji'
COLUMNS, TILE = 64, 20


def main():
    archive = Path(sys.argv[1])
    if hashlib.sha256(archive.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        raise SystemExit('Archive hash does not match the pinned Twemoji v15.1.0 source')
    DEST.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive) as source:
        files = sorted((m for m in source.getmembers()
                        if m.isfile() and m.name.startswith('twemoji-15.1.0/assets/72x72/')
                        and m.name.endswith('.png')), key=lambda m: Path(m.name).stem)
        rows = math.ceil(len(files) / COLUMNS)
        sheet = Image.new('RGBA', (COLUMNS * TILE, rows * TILE))
        identifiers = []
        rules = ['/* Generated by tools/build_emoji_sprites.py; Twemoji graphics: CC-BY 4.0. */',
                 '.markdown-body .emoji-sprite { display:inline-block; width:1.25em; height:1.25em; '
                 'margin:0 .08em; vertical-align:-.22em; overflow:hidden; text-indent:-9999px; '
                 'white-space:nowrap; background-image:url("./sprites.png"); '
                 f'background-size:{COLUMNS * 100}% {rows * 100}%; background-repeat:no-repeat; }}']
        for index, member in enumerate(files):
            image = Image.open(io.BytesIO(source.extractfile(member).read())).convert('RGBA')
            image = image.resize((TILE, TILE), Image.Resampling.LANCZOS)
            col, row = index % COLUMNS, index // COLUMNS
            sheet.paste(image, (col * TILE, row * TILE))
            identifiers.append(Path(member.name).stem)
        sheet = sheet.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
        sheet.save(DEST / 'sprites.png', optimize=True)
        (DEST / 'sprites.css').write_text('\n'.join(rules) + '\n')
        (DEST / 'sprites.js').write_text('// Generated Twemoji identifiers; see README.md and LICENSE-GRAPHICS.\nexport default ' + json.dumps(identifiers, separators=(',', ':')) + ';\n')
        (DEST / 'LICENSE-GRAPHICS').write_bytes(source.extractfile('twemoji-15.1.0/LICENSE-GRAPHICS').read())
    print(f'{len(identifiers)} emoji; {sheet.width}x{sheet.height}; {(DEST / "sprites.png").stat().st_size:,} PNG bytes')


if __name__ == '__main__':
    main()
